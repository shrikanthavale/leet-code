    public static String strip(String value) {
        int start = 0, end = value.length();
        while (start < end && whitespace(value.codePointAt(start))) {
            start += Character.charCount(value.codePointAt(start));
        }
        while (start < end && whitespace(value.codePointBefore(end))) {
            end -= Character.charCount(value.codePointBefore(end));
        }
        return value.substring(start, end);
    }

    public static int compare(String leftText, String rightText) {
        var left = leftText.codePoints().iterator();
        var right = rightText.codePoints().iterator();
        while (left.hasNext() && right.hasNext()) {
            int cmp = Integer.compare(left.nextInt(), right.nextInt());
            if (cmp != 0) {
                return cmp;
            }
        }
        return Boolean.compare(left.hasNext(), right.hasNext());
    }
