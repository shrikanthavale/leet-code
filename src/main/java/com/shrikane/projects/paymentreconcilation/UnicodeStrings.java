    public static String casefold(String value) {
        StringBuilder result = new StringBuilder();
        value.codePoints()
                .forEach(
                        codePoint ->
                                result.append(
                                        FOLD.getOrDefault(
                                                codePoint,
                                                new String(Character.toChars(codePoint)))));
        return result.toString();
    }

